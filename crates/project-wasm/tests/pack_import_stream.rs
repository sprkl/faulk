//! The `.faulkpack` import of a project with a large audio blob (#682): the store's Worker reads
//! the pack in the ranges the session asks for and writes the blob as it comes, so what the
//! import holds does not depend on the size of the blob. Generated data, nothing committed.
//!
//! This binary counts every byte its allocator holds and asserts that the peak of the import
//! stays far under the size of the blob. The pack is made first by the export session into a
//! temporary file (not counted), then imported from that file, the blob being checked chunk by
//! chunk as it comes out. Peak memory and time are printed:
//! `cargo test -p project-wasm --release --test pack_import_stream -- --nocapture`.

use std::alloc::{GlobalAlloc, Layout, System};
use std::io::{Read, Seek, SeekFrom, Write};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::Instant;

use project_wasm::{
    pw_inbox, pw_out, pw_pack_begin, pw_pack_feed, pw_pack_next, pw_unpack_begin, pw_unpack_step,
};
use sha2::{Digest, Sha256};

struct Counting;

static CURRENT: AtomicUsize = AtomicUsize::new(0);
static PEAK: AtomicUsize = AtomicUsize::new(0);

// SAFETY: forwards every call to the system allocator and only counts the bytes.
unsafe impl GlobalAlloc for Counting {
    unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
        // SAFETY: forwarded from the caller's contract.
        let ptr = unsafe { System.alloc(layout) };
        if !ptr.is_null() {
            let now = CURRENT.fetch_add(layout.size(), Ordering::Relaxed) + layout.size();
            PEAK.fetch_max(now, Ordering::Relaxed);
        }
        ptr
    }

    unsafe fn dealloc(&self, ptr: *mut u8, layout: Layout) {
        CURRENT.fetch_sub(layout.size(), Ordering::Relaxed);
        // SAFETY: forwarded from the caller's contract.
        unsafe { System.dealloc(ptr, layout) }
    }

    unsafe fn realloc(&self, ptr: *mut u8, layout: Layout, new_size: usize) -> *mut u8 {
        // SAFETY: forwarded from the caller's contract.
        let new = unsafe { System.realloc(ptr, layout, new_size) };
        if !new.is_null() {
            if new_size >= layout.size() {
                let now = CURRENT.fetch_add(new_size - layout.size(), Ordering::Relaxed)
                    + (new_size - layout.size());
                PEAK.fetch_max(now, Ordering::Relaxed);
            } else {
                CURRENT.fetch_sub(layout.size() - new_size, Ordering::Relaxed);
            }
        }
        new
    }
}

#[global_allocator]
static ALLOCATOR: Counting = Counting;

const BLOB_BYTES: u64 = 600 << 20;
const CHUNK: usize = 4 << 20;

/// The `index`th chunk of the generated blob: a noisy but compressible signal, the same every time.
fn chunk_at(index: u64, out: &mut Vec<u8>, size: usize) {
    out.clear();
    let mut state = 0x9E37_79B9_7F4A_7C15u64 ^ index.wrapping_mul(0xD1B5_4A32_D192_ED03);
    out.extend((0..size).map(|i| {
        state ^= state << 13;
        state ^= state >> 7;
        state ^= state << 17;
        ((i / 8) as u8).wrapping_add((state & 0x1f) as u8)
    }));
}

/// The blob's name: the hash of the generated bytes.
fn blob_name() -> String {
    let mut hash = Sha256::new();
    let mut chunk = Vec::with_capacity(CHUNK);
    let mut done = 0u64;
    let mut index = 0u64;
    while done < BLOB_BYTES {
        let size = CHUNK.min((BLOB_BYTES - done) as usize);
        chunk_at(index, &mut chunk, size);
        hash.update(&chunk);
        done += size as u64;
        index += 1;
    }
    let digest = hash.finalize();
    format!(
        "blobs/{}",
        digest
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect::<String>()
    )
}

fn put_inbox(bytes: &[u8]) {
    let ptr = pw_inbox(bytes.len() as u32);
    assert!(!ptr.is_null());
    // SAFETY: the inbox holds at least `bytes.len()` bytes.
    unsafe { core::ptr::copy_nonoverlapping(bytes.as_ptr(), ptr, bytes.len()) };
}

fn out_of(len: i32) -> &'static [u8] {
    assert!(len > 0, "error code {len}");
    // SAFETY: `pw_out` holds the `len` bytes of the last call, valid until the next one.
    unsafe { core::slice::from_raw_parts(pw_out(), len as usize) }
}

fn folder_frame(files: &[(String, Vec<u8>)], listed: &[(&str, u64)]) -> Vec<u8> {
    let mut frame = Vec::new();
    frame.extend(4u32.to_le_bytes());
    frame.extend(b"pack");
    for (path, bytes) in files {
        frame.extend((path.len() as u32).to_le_bytes());
        frame.extend(path.as_bytes());
        frame.push(0);
        frame.extend((bytes.len() as u64).to_le_bytes());
        frame.extend(bytes);
    }
    for (path, size) in listed {
        frame.extend((path.len() as u32).to_le_bytes());
        frame.extend(path.as_bytes());
        frame.push(1);
        frame.extend(size.to_le_bytes());
    }
    frame
}

/// The folder of the format's reference song.
fn song() -> Vec<(String, Vec<u8>)> {
    fn walk(dir: &std::path::Path, base: &str, files: &mut Vec<(String, Vec<u8>)>) {
        for entry in std::fs::read_dir(dir).unwrap() {
            let entry = entry.unwrap();
            let name = entry.file_name().into_string().unwrap();
            let path = if base.is_empty() {
                name
            } else {
                format!("{base}/{name}")
            };
            if entry.file_type().unwrap().is_dir() {
                walk(&entry.path(), &path, files);
            } else {
                files.push((path, std::fs::read(entry.path()).unwrap()));
            }
        }
    }
    let mut files = Vec::new();
    let dir =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../project/tests/reference/song");
    walk(&dir, "", &mut files);
    files
}

/// Writes the pack of the song plus the generated blob to `path` with the export session. The
/// song names its audio blob `ab` * 32 (its folder lacks it): it is renamed after the generated
/// blob, so the project refers to it and the export takes it.
fn write_pack(path: &std::path::Path, blob: &str) {
    let hash = blob.strip_prefix("blobs/").unwrap();
    let files: Vec<(String, Vec<u8>)> = song()
        .into_iter()
        .map(|(p, b)| match String::from_utf8(b) {
            Ok(text) => (p, text.replace(&"ab".repeat(32), hash).into_bytes()),
            // A lane blob, as it is.
            Err(e) => (p, e.into_bytes()),
        })
        .collect();
    let frame = folder_frame(&files, &[(blob, BLOB_BYTES)]);
    let mut pack = std::fs::File::create(path).unwrap();
    put_inbox(&frame);
    let begun = out_of(pw_pack_begin(frame.len() as u32));
    assert_eq!(begun[0], 0, "{}", String::from_utf8_lossy(&begun[1..]));
    let mut chunk = Vec::with_capacity(CHUNK);
    loop {
        let out = out_of(pw_pack_next());
        match out[0] {
            3 => {
                pack.write_all(&out[1..]).unwrap();
                break;
            }
            2 => {
                let n = u32::from_le_bytes(out[1..5].try_into().unwrap()) as usize;
                assert_eq!(std::str::from_utf8(&out[5..5 + n]).unwrap(), blob);
                pack.write_all(&out[5 + n..]).unwrap();
                let mut done = 0u64;
                let mut index = 0u64;
                while done < BLOB_BYTES {
                    let size = CHUNK.min((BLOB_BYTES - done) as usize);
                    chunk_at(index, &mut chunk, size);
                    put_inbox(&chunk);
                    let fed = out_of(pw_pack_feed(size as u32));
                    assert_eq!(fed[0], 0, "{}", String::from_utf8_lossy(&fed[1..]));
                    pack.write_all(&fed[1..]).unwrap();
                    done += size as u64;
                    index += 1;
                }
            }
            _ => panic!("{}", String::from_utf8_lossy(&out[1..])),
        }
    }
    pack.flush().unwrap();
}

#[test]
fn a_pack_with_a_600_mib_blob_is_imported_in_bounded_memory() {
    let blob = blob_name();
    let pack_path =
        std::env::temp_dir().join(format!("faulk-pack-import-{}.zip", std::process::id()));
    write_pack(&pack_path, &blob);
    let mut pack = std::fs::File::open(&pack_path).unwrap();
    let len = pack.metadata().unwrap().len();

    let baseline = CURRENT.load(Ordering::Relaxed);
    PEAK.store(baseline, Ordering::Relaxed);
    let started = Instant::now();
    let mut piece = Vec::with_capacity(1 << 20);
    let mut expected = Vec::with_capacity(CHUNK);
    // The blob as it comes out, compared with the generated one as a stream.
    let mut checked = 0u64;
    let mut pending: Vec<u8> = Vec::with_capacity(2 * CHUNK);
    let mut index = 0u64;
    let mut blob_size = None;
    let mut out = out_of(pw_unpack_begin(len as u32, (len >> 32) as u32)).to_vec();
    let texts = loop {
        out = match out[0] {
            0 => {
                let offset = u64::from_le_bytes(out[1..9].try_into().unwrap());
                let n = u32::from_le_bytes(out[9..13].try_into().unwrap()) as usize;
                piece.resize(n, 0);
                pack.seek(SeekFrom::Start(offset)).unwrap();
                pack.read_exact(&mut piece).unwrap();
                put_inbox(&piece);
                out_of(pw_unpack_step(n as u32)).to_vec()
            }
            2 => {
                let size = u64::from_le_bytes(out[1..9].try_into().unwrap());
                let n = u32::from_le_bytes(out[9..13].try_into().unwrap()) as usize;
                let path = std::str::from_utf8(&out[13..13 + n]).unwrap();
                if path == blob {
                    blob_size = Some(size);
                }
                out_of(pw_unpack_step(0)).to_vec()
            }
            3 => {
                if blob_size.is_some() && checked < BLOB_BYTES {
                    pending.extend_from_slice(&out[1..]);
                    while pending.len() >= CHUNK
                        || (checked + pending.len() as u64 == BLOB_BYTES && !pending.is_empty())
                    {
                        let size = CHUNK.min((BLOB_BYTES - checked) as usize);
                        chunk_at(index, &mut expected, size);
                        assert!(pending[..size] == expected[..], "chunk {index} differs");
                        pending.drain(..size);
                        checked += size as u64;
                        index += 1;
                    }
                }
                out_of(pw_unpack_step(0)).to_vec()
            }
            4 => out_of(pw_unpack_step(0)).to_vec(),
            5 => break out.len(),
            _ => panic!("{}", String::from_utf8_lossy(&out[1..])),
        };
    };
    let import_ms = started.elapsed().as_millis();
    let peak = PEAK.load(Ordering::Relaxed) - baseline;
    drop(pack);
    let _ = std::fs::remove_file(&pack_path);

    assert_eq!(blob_size, Some(BLOB_BYTES));
    assert_eq!(checked, BLOB_BYTES, "the whole blob came out");
    println!(
        "import: pack {} MiB, blob {} MiB, import {import_ms} ms, end frame {texts} bytes, peak {:.1} MiB over the baseline",
        len >> 20,
        BLOB_BYTES >> 20,
        peak as f64 / (1 << 20) as f64
    );
    // The blob, or the pack, held whole would be hundreds of MiB.
    assert!(
        peak < 48 << 20,
        "the import held {} MiB for a {} MiB blob",
        peak >> 20,
        BLOB_BYTES >> 20
    );
}
