// Generates the TypeScript types of commands and protocol messages from the Rust
// schema (`cargo run -p protocol --bin export-schema`). The output is committed;
// CI fails when regenerating it gives a diff.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const root = fileURLToPath(new URL('../..', import.meta.url))
const out = fileURLToPath(new URL('../src/lib/generated/', import.meta.url))
const cargo = process.env.CARGO ?? 'cargo'

const json = execFileSync(cargo, ['run', '-q', '-p', 'protocol', '--bin', 'export-schema'], {
  cwd: root,
  encoding: 'utf8',
})
const bundle = JSON.parse(json)
writeFileSync(out + 'schema.json', JSON.stringify(bundle, null, 2) + '\n')

const options = { bannerComment: '', additionalProperties: false, format: false, strictIndexSignatures: true }
const parts = [
  '// Generated by scripts/gen-protocol.mjs from the Rust crates `commands` and `protocol`. Do not edit.',
  '/* eslint-disable */',
  `export const PROTOCOL_VERSION = ${bundle.protocol_version} as const`,
  `export const PARAM_IDS = ${JSON.stringify(bundle.param_ids)} as const`,
  `export const PARAM_DEFAULTS = ${JSON.stringify(bundle.param_defaults)} as const`,
  await compile(bundle.command, 'Command', options),
  await compile(bundle.client_message, 'ClientMessage', { ...options, declareExternallyReferenced: false }),
  await compile(bundle.server_message, 'ServerMessage', { ...options, declareExternallyReferenced: false }),
  await compile(bundle.server_message.$defs.MidiInput, 'MidiInput', options),
]
writeFileSync(out + 'protocol.ts', parts.join('\n') + '\n')
console.log('generated src/lib/generated/protocol.ts')
