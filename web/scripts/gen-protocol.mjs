// Generates the TypeScript types of commands and protocol messages from the Rust
// schema (`cargo run -p protocol --bin export-schema`). The output is committed;
// CI fails when regenerating it gives a diff.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'
import { mergeRoots } from './schema-merge.mjs'

const root = fileURLToPath(new URL('../..', import.meta.url))
const out = fileURLToPath(new URL('../src/lib/generated/', import.meta.url))
const cargo = process.env.CARGO ?? 'cargo'

const json = execFileSync(cargo, ['run', '-q', '-p', 'protocol', '--bin', 'export-schema'], {
  cwd: root,
  encoding: 'utf8',
  // The bundle repeats the shared definitions in every tool of the catalog: it passed the
  // 1 MB default of execFileSync with the clip commands.
  maxBuffer: 256 * 1024 * 1024,
})
const bundle = JSON.parse(json)
writeFileSync(out + 'schema.json', JSON.stringify(bundle, null, 2) + '\n')

// The four roots are compiled as one schema (see `schema-merge.mjs`).
const roots = {
  Command: bundle.command.input,
  CommandOutput: bundle.command.output,
  ClientMessage: bundle.client_message,
  ServerMessage: bundle.server_message,
  // The page's project core (PR-4): what each call of `src/lib/project/core.ts` returns, one
  // root per schema of `project_core`, named in PascalCase (`run_report` → `RunReport`).
  ...Object.fromEntries(
    Object.entries(bundle.project_core).map(([key, schema]) => [
      key.replace(/(^|_)([a-z])/g, (_, __, c) => c.toUpperCase()),
      schema,
    ]),
  ),
}
const defs = mergeRoots(roots)
/** @type {import('json-schema-to-typescript').JSONSchema} */
const wrapper = {
  title: 'Bundle',
  type: 'object',
  properties: Object.fromEntries(Object.keys({ ...roots, MidiInput: 0 }).map((k) => [k, { $ref: `#/$defs/${k}` }])),
  required: [...Object.keys(roots), 'MidiInput'],
  additionalProperties: false,
  $defs: defs,
}
if (!defs.MidiInput) throw new Error('the schema bundle has no MidiInput definition')
const types = await compile(wrapper, 'Bundle', {
  bannerComment: '',
  additionalProperties: false,
  format: false,
  strictIndexSignatures: true,
})
const parts = [
  '// Generated by scripts/gen-protocol.mjs from the Rust crates `commands` and `protocol`. Do not edit.',
  '/* eslint-disable */',
  `export const PROTOCOL_VERSION = ${bundle.protocol_version} as const`,
  `export const PARAM_IDS = ${JSON.stringify(bundle.param_ids)} as const`,
  `export const PARAM_DEFAULTS = ${JSON.stringify(bundle.param_defaults)} as const`,
  '/** A parameter id of the built-in synth, as `device.set_param` takes it. */',
  'export type SynthParam = keyof typeof PARAM_IDS',
  '/** The ids of the one synth until the project runs in the page (PR-4, PR-5), and its device kind. */',
  `export const SINGLE_SYNTH = ${JSON.stringify(bundle.single_synth)} as const`,
  '/** The descriptor of every built-in device (CT-5, DV-1): the UI builds the device panels from them. */',
  `export const DEVICES = ${JSON.stringify(bundle.devices)} as const`,
  // The wrapper only exists to declare the roots together.
  types.replace(/^export interface Bundle \{[^}]*\}\n/m, ''),
]
writeFileSync(out + 'protocol.ts', parts.join('\n') + '\n')
console.log('generated src/lib/generated/protocol.ts')
